package com.jevfilter;

import java.util.Locale;
import java.util.regex.Pattern;

/**
 * Локальный стоп-лист: то, что нельзя снимать ни при каких обстоятельствах, решается до сети.
 *
 * Зачем он нужен, если есть Джев:
 *  1. Код подтверждения нельзя терять никогда. Если Джев промолчит, ошибётся или сеть отвалится,
 *     решение всё равно должно быть «оставить» - и оно принимается, не выходя из телефона.
 *  2. Сырой текст с кодом и суммой не уходит в OpenRouter вообще: до запроса дело не доходит.
 *  3. Это быстрее: попадание в стоп-лист не занимает поток в пуле и не ждёт ответа.
 *
 * Проверка идёт ПОСЛЕ списка приложений: чужое уведомление мы и так не трогаем.
 * Ошибка в сторону «оставить» дешевле ошибки в сторону «снять», поэтому список широкий.
 */
final class StopList {

    /**
     * «код 4321», «code: 1234», «пароль - 1234», но НЕ «промокод 12345».

     * Слово должно стоять отдельно: перед ним и после него не буква. Иначе рекламные
     * «промокод», «код товара», «qr-код» навсегда защитили бы себя от фильтра.
     */
    private static final Pattern CODE_NEAR_DIGITS = Pattern.compile(
            "(?<![а-яёa-z])(код|code|pin|otp|пароль|password)(?![а-яёa-z])[^\\d\\n]{0,14}\\d{4,8}",
            Pattern.CASE_INSENSITIVE);

    /** Четыре-восемь цифр подряд: код, сумма, номер заказа. Само по себе не повод оставить. */
    private static final Pattern DIGITS = Pattern.compile("(?<!\\d)\\d{4,8}(?!\\d)");

    private static final Pattern ANY_DIGIT = Pattern.compile("\\d");

    /** Что искать в заголовке и тексте и что написать в журнале, если нашли. */
    private static final String[][] WORDS = {
            // коды и доступ
            {"код подтвержд", "код подтверждения"},
            {"подтвержд", "подтверждение"},
            {"код доступа", "код доступа"},
            {"код для входа", "код для входа"},
            {"одноразов", "одноразовый код"},
            {"никогда никому", "предупреждение о коде"},
            {"не сообща", "предупреждение о коде"},
            {"пароль", "пароль"},
            {"пин-код", "пин-код"},
            {"pin code", "пин-код"},
            {"otp", "одноразовый код"},
            {"one-time", "одноразовый код"},
            {"one time", "одноразовый код"},
            {"verification", "код подтверждения"},
            {"verify", "код подтверждения"},
            {"authenticat", "подтверждение входа"},
            {"двухфактор", "двухфакторная аутентификация"},
            {"2fa", "двухфакторная аутентификация"},
            {"cvv", "cvv"},
            {"cvc", "cvc"},
            {"3-d secure", "3-d secure"},
            {"3d secure", "3-d secure"},
            // деньги
            {"списан", "списание денег"},
            {"зачислен", "зачисление денег"},
            {"перевод", "перевод денег"},
            {"баланс", "баланс"},
            {"платёж", "платёж"},
            {"платеж", "платёж"},
            {"операци", "операция по счёту"},
            {"пополнен", "пополнение счёта"},
            {"снятие", "снятие денег"},
            {"задолженност", "задолженность"},
            {"штраф", "штраф"},
            {"квитанц", "квитанция"},
            // безопасность аккаунта
            {"вход в", "вход в аккаунт"},
            {"новое устройство", "новое устройство"},
            {"подозрительн", "подозрительная активность"},
            {"безопасност", "безопасность аккаунта"},
            {"заблокирован", "блокировка"},
            {"мошенник", "мошенничество"},
            {"взлом", "взлом аккаунта"},
    };

    private StopList() {
    }

    /**
     * Причина оставить уведомление, не спрашивая Джева, или null, если стоп-лист молчит.
     * pkg нужен, чтобы банк и госуслуги не уходили в сеть даже своим обычным уведомлением.
     */
    static String reason(String pkg, String title, String text) {
        try {
            String risk = Prefs.riskNote(pkg);
            if (risk != null && (risk.startsWith("банк") || risk.startsWith("госуслуги")
                    || risk.startsWith("системное"))) {
                return risk;
            }

            String hay = hay(title, text);
            // Текст, которого мы не видим, трогать нельзя: на Android 15+ так выглядит
            // уведомление с кодом, у которого система вырезала содержимое.
            if (hay.trim().length() == 0) return "текст не читается";

            for (String[] rule : WORDS) {
                if (hay.contains(rule[0])) return rule[1];
            }
            if (CODE_NEAR_DIGITS.matcher(hay).find()) return "похоже на код";
            return null;
        } catch (Throwable t) {
            // сомнение трактуется в пользу человека
            return "ошибка стоп-листа";
        }
    }

    /**
     * Есть ли в уведомлении цифры, похожие на код или сумму.
     *
     * Само по себе это не повод оставить - в рекламе полно цен, промокодов и номеров заказов, -
     * но повод требовать от Джева большей уверенности. Голое «4-8 цифр значит оставить»
     * защитило бы от фильтра половину спама.
     */
    static boolean hasDigits(String title, String text) {
        try {
            return DIGITS.matcher(hay(title, text)).find();
        } catch (Throwable t) {
            return true;
        }
    }

    /** Тот же текст, но без цифр: для журнала, чтобы коды не оседали в логе открытым текстом. */
    static String mask(String s) {
        if (s == null || s.length() == 0) return "";
        try {
            return ANY_DIGIT.matcher(s).replaceAll("•");
        } catch (Throwable t) {
            return "";
        }
    }

    private static String hay(String title, String text) {
        return ((title == null ? "" : title) + " \n " + (text == null ? "" : text))
                .toLowerCase(Locale.ROOT);
    }
}
